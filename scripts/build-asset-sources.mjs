import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

export const ASSET_COMMIT = '08fc27160defd7c6e2b01638a26bcb5b7b3e9ae1';
export const ASSET_THRESHOLD = 128 * 1024;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mediaExtensions = new Set(['.png', '.jpg', '.jpeg', '.webp', '.avif', '.gif', '.svg', '.mp4', '.webm', '.mp3', '.wav', '.ogg', '.m4a', '.aac', '.flac', '.woff', '.woff2', '.otf', '.ttf', '.bin']);
const assetFolders = ['demos', 'previews', 'research', 'docs', 'vendor'];

// These URLs identify immutable, byte-preserved media. Executable JS/CSS stays
// local: GitHub Raw's MIME/nosniff response is not a script distribution service.
export function buildAssetSources(sourceRoot = root, commit = ASSET_COMMIT) {
  if (!/^[a-f\d]{40}$/.test(commit)) throw new Error('Asset commit must be a published full 40-character commit SHA.');
  const result = spawnSync('git', ['-c', `safe.directory=${sourceRoot}`, '-C', sourceRoot, 'ls-tree', '-r', '-z', commit], {encoding:'utf8', maxBuffer:16 * 1024 * 1024});
  if (result.error || result.status !== 0) throw new Error('Cannot read asset commit. Commit and push the media first, then regenerate with --commit <published-full-sha>. ' + (result.error?.message || result.stderr.trim()));
  const committed = new Map(result.stdout.split('\0').filter(Boolean).map(record => {
    const tab = record.indexOf('\t');
    const [mode, type, blob] = record.slice(0, tab).split(' ');
    return [record.slice(tab + 1), {mode, type, blob}];
  }));
  const baseUrl = `https://raw.githubusercontent.com/MIBXR/design-atlas/${commit}/`;
  const assets = {};
  function visit(directory) {
    for (const item of fs.readdirSync(directory, {withFileTypes:true}).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
      const target = path.join(directory, item.name);
      const stat = fs.lstatSync(target);
      if (stat.isDirectory()) visit(target);
      else if (!stat.isFile()) throw new Error('Asset sources cannot contain links or special files: ' + target);
      else if (mediaExtensions.has(path.extname(item.name).toLowerCase()) && stat.size >= ASSET_THRESHOLD) {
        const canonical = path.relative(sourceRoot, target).split(path.sep).join('/');
        const encoded = canonical.split('/').map(encodeURIComponent).join('/');
        const bytes = fs.readFileSync(target);
        const gitBlob = createHash('sha1').update(Buffer.from(`blob ${bytes.length}\0`)).update(bytes).digest('hex');
        const published = committed.get(canonical);
        if (!published || published.type !== 'blob' || !['100644', '100755'].includes(published.mode) || published.blob !== gitBlob) throw new Error(`Media does not match commit ${commit}: ${canonical}. Commit and push this asset first, then regenerate with --commit <published-full-sha>.`);
        assets[canonical] = {url:baseUrl + encoded, bytes:stat.size, sha256:createHash('sha256').update(bytes).digest('hex')};
      }
    }
  }
  for (const folder of assetFolders) {
    const target = path.join(sourceRoot, folder);
    if (fs.existsSync(target)) visit(target);
  }
  return {commit, baseUrl, thresholdBytes:ASSET_THRESHOLD, assets};
}

export function serializeAssetSources(sources) {
  return '// Fixed source commit; media bytes are preserved. Generated by scripts/build-asset-sources.mjs.\nglobalThis.DesignAtlasAssetSources = ' + JSON.stringify(sources, null, 2) + ';\n';
}

// Read the generated data without evaluating JavaScript. Static builds use this
// committed manifest; they never silently pin new media to an older commit.
export function loadAssetSources(sourceRoot = root) {
  const text = fs.readFileSync(path.join(sourceRoot, 'asset-sources.js'), 'utf8');
  const match = text.match(/(?:globalThis|window|self)\.DesignAtlasAssetSources\s*=\s*(\{[\s\S]*\})\s*;\s*$/);
  if (!match) throw new Error('asset-sources.js must contain the generated DesignAtlasAssetSources JSON assignment.');
  const sources = JSON.parse(match[1]);
  const expectedBase = `https://raw.githubusercontent.com/MIBXR/design-atlas/${sources.commit}/`;
  if (!/^[a-f\d]{40}$/.test(sources.commit) || sources.baseUrl !== expectedBase || sources.thresholdBytes !== ASSET_THRESHOLD || !sources.assets || Array.isArray(sources.assets)) throw new Error('Invalid immutable asset-source manifest. Regenerate it with --commit <published-full-sha>.');
  for (const [canonical, asset] of Object.entries(sources.assets)) {
    if (!canonical || canonical.startsWith('/') || canonical.includes('\\') || canonical.split('/').some(part => !part || part === '.' || part === '..')) throw new Error('Invalid canonical asset path: ' + canonical);
    const target = path.join(sourceRoot, canonical);
    const stat = fs.lstatSync(target, {throwIfNoEntry:false});
    const expectedUrl = expectedBase + canonical.split('/').map(encodeURIComponent).join('/');
    if (!stat?.isFile() || stat.size !== asset.bytes || asset.bytes < ASSET_THRESHOLD || asset.url !== expectedUrl || !/^[a-f\d]{64}$/.test(asset.sha256) || createHash('sha256').update(fs.readFileSync(target)).digest('hex') !== asset.sha256) throw new Error('Asset-source bytes or URL do not match: ' + canonical + '. Commit/push changed media and regenerate the manifest before a static build.');
  }
  return sources;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argumentsList = process.argv.slice(2);
  if (argumentsList.length && (argumentsList.length !== 2 || argumentsList[0] !== '--commit')) throw new Error('Usage: node scripts/build-asset-sources.mjs [--commit <published-full-sha>]');
  const sources = buildAssetSources(root, argumentsList[1] || ASSET_COMMIT);
  fs.writeFileSync(path.join(root, 'asset-sources.js'), serializeAssetSources(sources), 'utf8');
  console.log(`Mapped ${Object.keys(sources.assets).length} media assets (${Object.values(sources.assets).reduce((sum, item) => sum + item.bytes, 0)} bytes) to fixed GitHub commit ${sources.commit}.`);
}
